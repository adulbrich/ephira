/**
 * PreToolUse on Edit and Write: the files nobody hand-edits, with the reason
 * each time so the model does the right thing instead.
 *
 * Answers with the JSON deny shape rather than exit 2 so the reason reaches
 * the model verbatim and the turn continues.
 *
 * A migration already on `origin/main` is refused because it has shipped:
 * a device that ran it never runs it again, so an edit reaches fresh installs
 * only and the two populations diverge (docs/adr/0002). A new `.sql` file, the
 * journal and `drizzle/migrations.js` stay editable.
 */
import { git, locate, readInput } from "./lib.mjs";

const PREFIXES = [
  [
    "ios/",
    "generated by `expo prebuild`; change `app.json` (its `plugins` list configures the native projects) and rebuild",
  ],
  [
    "android/",
    "generated by `expo prebuild`; change `app.json` (its `plugins` list configures the native projects) and rebuild",
  ],
  [
    ".expo/",
    "generated by Expo; `npx expo start` or `npx expo customize` regenerates it",
  ],
  ["credentials/", "signing material; tell the user what to change"],
  ["docs/dist/", "the built website; edit `docs/src/` and rebuild"],
];

const FILES = new Map([
  ["credentials.json", "signing material; tell the user what to change"],
  [
    "package-lock.json",
    "written by npm; change `package.json` and run `npm install`",
  ],
  [
    "docs/package-lock.json",
    "written by npm; change `docs/package.json` and run `npm install` in `docs/`",
  ],
]);

const SHIPPED_MIGRATION = /^drizzle\/\d{4}_[^/]+\.sql$/;

function reasonFor(root, path) {
  const prefix = PREFIXES.find(([p]) => path.startsWith(p));
  if (prefix) {
    return prefix[1];
  }
  if (FILES.has(path)) {
    return FILES.get(path);
  }
  if (
    SHIPPED_MIGRATION.test(path) &&
    git(root, ["ls-tree", "--name-only", "origin/main", "--", path]) === path
  ) {
    return "a migration that has shipped; devices that ran it never run it again. Write the next numbered migration instead (docs/adr/0002)";
  }
  return null;
}

const input = readInput();
// The rules describe this repository; an edit anywhere else passes.
const found = locate(input.tool_input?.file_path ?? "");
const path = found?.path ?? "";
const reason = found ? reasonFor(found.root, path) : null;

if (reason) {
  process.stdout.write(
    JSON.stringify({
      hookSpecificOutput: {
        hookEventName: "PreToolUse",
        permissionDecision: "deny",
        permissionDecisionReason: `${path} is ${reason}.`,
      },
    }),
  );
}
